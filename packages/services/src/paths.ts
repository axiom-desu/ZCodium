/* path 规则集中维护：旧 task 快照与 provider 配置路径仍在这里收口。 */
import { lstatSync } from "node:fs";
import { cp } from "node:fs/promises";
import { createHash } from "node:crypto";
import { basename, join, win32 } from "node:path";
import { homedir } from "node:os";
import {
  DATA_BASE_DIR_FORBIDDEN_WINDOWS_INSTALL_DIR_ERROR_CODE,
  ZCODE_APP_CONFIG_SUBDIR_NAME,
  ZCODE_USER_DATA_DIR_NAME,
} from "@zcode/shared";

let _dataBaseDir: string | null = null;
export const ZCODE_WINDOWS_APP_INSTALL_DIR_ENV = "ZCODE_WINDOWS_APP_INSTALL_DIR";
const envDataBaseDir = process.env.ZCODE_DATA_BASE_DIR?.trim() || null;
const defaultDataBaseDir = process.env.HOME?.trim() || homedir();

interface DataBaseDirTargetValidationOptions {
  platform?: NodeJS.Platform | string;
  env?: Record<string, string | undefined>;
  appInstallDir?: string | null;
}

type DataBaseDirTargetValidationResult =
  | { ok: true }
  | {
      ok: false;
      code: typeof DATA_BASE_DIR_FORBIDDEN_WINDOWS_INSTALL_DIR_ERROR_CODE;
      forbiddenDir: string;
    };

/** Set the base directory for app data (replaces homedir() prefix). */
export function setDataBaseDir(dir: string | null): void {
  _dataBaseDir = dir?.trim() || null;
}

/** Get the current base directory. Priority: setDataBaseDir() > env ZCODE_DATA_BASE_DIR > homedir(). */
export function getDataBaseDir(): string {
  if (_dataBaseDir) return _dataBaseDir;
  if (envDataBaseDir) return envDataBaseDir;
  // 服务实例会启动后台刷新任务；若每次调用都动态读取 HOME，
  // 测试或宿主切换环境变量后，旧实例可能把数据写到新实例目录。
  return defaultDataBaseDir;
}

/** {dataBaseDir}/.zcodium */
export function getZCodeDataRootDir(): string {
  return join(getDataBaseDir(), ZCODE_USER_DATA_DIR_NAME);
}

/**
 * 用户级默认指令文件所在的 home 目录。
 *
 * 走 `HOME`/`USERPROFILE`/`homedir()`，**不读** `ZCODE_DATA_BASE_DIR`/桌面 home 覆盖：
 * CLI 的 `findDefaultUserInstructionFile` 用同一规则解析少数用户级指令文件，
 * 设置页写的文件必须是 Agent 实际读取的那个。
 */
function resolveAgentUserInstructionsHomeDir(
  env: Record<string, string | undefined> = process.env,
): string {
  const envHome = env.HOME?.trim() || env.USERPROFILE?.trim();
  return envHome && envHome.length > 0 ? envHome : homedir();
}

/** `{home}/.zcodium/AGENTS.md`：个性化指令的唯一事实源（与 CLI 读取路径一致）。 */
export function getAgentUserInstructionsFilePath(
  env: Record<string, string | undefined> = process.env,
): string {
  return join(resolveAgentUserInstructionsHomeDir(env), ZCODE_USER_DATA_DIR_NAME, "AGENTS.md");
}

